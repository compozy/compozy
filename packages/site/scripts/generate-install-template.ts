import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(siteRoot, "..", "..");
const templatePath = resolve(repoRoot, "scripts", "install.template.sh");
const outputPath = resolve(siteRoot, "lib", "install", "template-content.ts");

const template = readFileSync(templatePath, "utf8");
if (!template.includes("__COMPOZY_PINNED_VERSION__")) {
  throw new Error(
    `install template is missing the __COMPOZY_PINNED_VERSION__ placeholder: ${templatePath}`
  );
}

const moduleSource = [
  "// Code generated by scripts/generate-install-template.ts from scripts/install.template.sh. DO NOT EDIT.",
  `export const INSTALL_SCRIPT_TEMPLATE = ${JSON.stringify(template)};`,
  "",
].join("\n");

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, moduleSource, "utf8");
console.log(`generated ${outputPath}`);
