// Builds the product logo module and icon sets from the brand sources in public/brand
// (ADR-004: vector lettering, raster symbol until a hand-drawn symbol vector exists).
//
// Outputs:
//   packages/ui/src/components/custom/logo-symbol.generated.ts    symbol data: URIs (64 / 256 px)
//   packages/ui/src/components/custom/logo-wordmark.generated.ts  wordmark path + lockup geometry
//   web/public/, packages/site/public/
//                     favicon.svg/.ico, apple-touch-icon, icon-192/512, icon-maskable-512, manifest
//   packages/site/lib/og/logo-assets.generated.ts, packages/launch-video/src/brand/logo-assets.generated.ts
//                     symbol data: URI + wordmark/lockup geometry for renderers that cannot import
//                     @compozy/ui (next/og Satori, the Remotion bundle)
//   imgs/             README hero lockups (dark default, light <picture> source)
//   desktop/build/    icon.icns (macOS iconutil), icon.png (512, also the Linux icon), icon.ico,
//                     tray/ menu-bar templates (idle / working / attention, @2x)
//
// Run with `bun run logos` in packages/brand. icon.icns needs macOS `iconutil`; elsewhere the
// script keeps the committed icns and says so.
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

import sharp from "sharp";

const ROOT = join(import.meta.dirname, "..", "..", "..");
const BRAND = join(ROOT, "packages", "brand", "public", "brand");
const PNG = join(BRAND, "png");
const SVG = join(BRAND, "svg");
const TRAY = join(BRAND, "product", "tray");
const UI_CUSTOM = join(ROOT, "packages", "ui", "src", "components", "custom");
const WEB_PUBLIC = join(ROOT, "web", "public");
const SITE_PUBLIC = join(ROOT, "packages", "site", "public");
const LOGO_ASSET_MODULES = [
  join(ROOT, "packages", "site", "lib", "og", "logo-assets.generated.ts"),
  join(ROOT, "packages", "launch-video", "src", "brand", "logo-assets.generated.ts"),
];
const README_IMGS = join(ROOT, "imgs");
const DESKTOP_BUILD = join(ROOT, "desktop", "build");

const SYMBOL_SOURCE = join(PNG, "compozy-symbol-618.png");
const APP_ICON_SOURCE = join(PNG, "compozy-app-icon-1024.png");
const WORDMARK_SOURCE = join(SVG, "compozy-wordmark-white.svg");
const LOCKUP_SOURCE = join(SVG, "compozy-lockup-dark.svg");
const MANIFEST_COLOR = "#0a0a0a";
// ADR-004 budget for both symbol rasters together, measured on the PNG bytes.
const SYMBOL_BUDGET_BYTES = 40 * 1024;

const rel = (path: string) => relative(ROOT, path);
const written: string[] = [];

function write(path: string, data: string | Buffer) {
  writeFileSync(path, data);
  written.push(rel(path));
}

function copy(from: string, to: string) {
  copyFileSync(from, to);
  written.push(rel(to));
}

function header(sources: string[]) {
  return [
    "// Generated by packages/brand/scripts/build-logos.ts from:",
    ...sources.map(source => `//   ${rel(source)}`),
    "// Do not edit by hand. Run `bun run logos` in packages/brand to refresh.",
    "",
  ].join("\n");
}

// Icons stay truecolor; the symbol rasters inlined into the UI bundle are palette-quantized
// (libimagequant) to fit the ADR-004 budget.
async function resizePng(source: string, size: number, palette = false) {
  return sharp(source)
    .resize(size, size, { kernel: "lanczos3" })
    .png(palette ? { palette, quality: 100, effort: 10 } : { compressionLevel: 9, palette })
    .toBuffer();
}

const dataUri = (png: Buffer) => `data:image/png;base64,${png.toString("base64")}`;

// ---------- svg parsing (sources are emitted by the new-branding build-logos script) ----------

function attr(tag: string, name: string) {
  const match = new RegExp(`\\s${name}="([^"]*)"`).exec(tag);
  if (!match?.[1]) throw new Error(`missing ${name}="…" in ${tag.slice(0, 80)}`);
  return match[1];
}

function firstTag(svg: string, tag: string, source: string) {
  const match = new RegExp(`<${tag}\\s[^>]*>`).exec(svg);
  if (!match) throw new Error(`no <${tag}> in ${rel(source)}`);
  return match[0];
}

function moveTo(d: string) {
  const match = /^M\s*(-?[\d.]+)[\s,]+(-?[\d.]+)/.exec(d);
  if (!match?.[1] || !match[2]) throw new Error(`path does not start with an absolute moveto`);
  return { x: Number(match[1]), y: Number(match[2]) };
}

const round = (n: number) => Math.round(n * 100) / 100;

function readWordmark() {
  const svg = readFileSync(WORDMARK_SOURCE, "utf8");
  const paths = svg.match(/<path\s[^>]*>/g) ?? [];
  if (paths.length !== 1 || !paths[0]) {
    throw new Error(`${rel(WORDMARK_SOURCE)} must hold exactly one path (got ${paths.length})`);
  }
  return {
    viewBox: attr(firstTag(svg, "svg", WORDMARK_SOURCE), "viewBox"),
    d: attr(paths[0], "d"),
  };
}

function readLockup(wordmarkD: string) {
  const svg = readFileSync(LOCKUP_SOURCE, "utf8");
  const image = firstTag(svg, "image", LOCKUP_SOURCE);
  const textPath = firstTag(svg, "path", LOCKUP_SOURCE);
  const inLockup = moveTo(attr(textPath, "d"));
  const inWordmark = moveTo(wordmarkD);
  return {
    viewBox: attr(firstTag(svg, "svg", LOCKUP_SOURCE), "viewBox"),
    symbol: {
      x: round(Number(attr(image, "x"))),
      y: round(Number(attr(image, "y"))),
      size: round(Number(attr(image, "width"))),
    },
    wordmark: { x: round(inLockup.x - inWordmark.x), y: round(inLockup.y - inWordmark.y) },
  };
}

// ---------- ico: PNG-compressed entries (Vista+), one per size ----------

function encodeIco(images: { size: number; png: Buffer }[]) {
  const head = Buffer.alloc(6);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = 6 + images.length * 16;
  const entries = images.map(({ size, png }) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0);
    entry.writeUInt8(size >= 256 ? 0 : size, 1);
    entry.writeUInt16LE(1, 4);
    entry.writeUInt16LE(32, 6);
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += png.length;
    return entry;
  });
  return Buffer.concat([head, ...entries, ...images.map(image => image.png)]);
}

// ---------- outputs ----------

async function buildUiModules() {
  const png64 = await resizePng(SYMBOL_SOURCE, 64, true);
  const png256 = await resizePng(SYMBOL_SOURCE, 256, true);
  const total = png64.length + png256.length;
  if (total > SYMBOL_BUDGET_BYTES) {
    throw new Error(`symbol rasters are ${total} B, over the ${SYMBOL_BUDGET_BYTES} B budget`);
  }
  write(
    join(UI_CUSTOM, "logo-symbol.generated.ts"),
    `${header([SYMBOL_SOURCE])}
// Interim raster symbol (ADR-004). Both include the source's 4% transparent padding.
export const LOGO_SYMBOL_PNG_64 = "${dataUri(png64)}";

export const LOGO_SYMBOL_PNG_256 = "${dataUri(png256)}";
`
  );

  const wordmark = readWordmark();
  const lockup = readLockup(wordmark.d);
  write(
    join(UI_CUSTOM, "logo-wordmark.generated.ts"),
    `${header([WORDMARK_SOURCE, LOCKUP_SOURCE])}
export const LOGO_WORDMARK = ${JSON.stringify(wordmark)} as const;

export const LOGO_LOCKUP = ${JSON.stringify(lockup)} as const;
`
  );
  return { png64, png256, wordmark, lockup };
}

type LogoAssets = Awaited<ReturnType<typeof buildUiModules>>;

// Package-local copies of the @compozy/ui logo data for renderers that cannot resolve that
// package's generated modules (no runtime dependency on packages/brand or packages/ui).
function buildLogoAssetModules({ png256, wordmark, lockup }: LogoAssets) {
  for (const path of LOGO_ASSET_MODULES) {
    write(
      path,
      `${header([SYMBOL_SOURCE, WORDMARK_SOURCE, LOCKUP_SOURCE])}
// Interim raster symbol (ADR-004), 256 px with the source's 4% transparent padding.
export const LOGO_SYMBOL_PNG = "${dataUri(png256)}";

export const LOGO_WORDMARK = ${JSON.stringify(wordmark)} as const;

export const LOGO_LOCKUP = ${JSON.stringify(lockup)} as const;
`
    );
  }
}

function buildReadmeLockups() {
  copy(join(PNG, "compozy-lockup-dark-256h.png"), join(README_IMGS, "compozy-lockup-dark.png"));
  copy(join(PNG, "compozy-lockup-light-256h.png"), join(README_IMGS, "compozy-lockup-light.png"));
}

async function buildWebIcons(out: string, symbol64: Buffer) {
  write(
    join(out, "favicon.svg"),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64"><image href="${dataUri(symbol64)}" width="64" height="64"/></svg>\n`
  );
  write(
    join(out, "favicon.ico"),
    encodeIco(
      [16, 32, 48].map(size => ({
        size,
        png: readFileSync(join(PNG, `compozy-symbol-${size}.png`)),
      }))
    )
  );
  copy(join(PNG, "compozy-app-icon-180.png"), join(out, "apple-touch-icon.png"));
  copy(join(PNG, "compozy-app-icon-192.png"), join(out, "icon-192.png"));
  copy(join(PNG, "compozy-app-icon-512.png"), join(out, "icon-512.png"));
  copy(join(PNG, "compozy-maskable-512.png"), join(out, "icon-maskable-512.png"));
  const manifest = {
    name: "CompozyOS",
    short_name: "CompozyOS",
    icons: [
      { src: "/icon-192.png", sizes: "192x192", type: "image/png" },
      { src: "/icon-512.png", sizes: "512x512", type: "image/png" },
      { src: "/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
    ],
    theme_color: MANIFEST_COLOR,
    background_color: MANIFEST_COLOR,
    display: "standalone",
  };
  write(join(out, "site.webmanifest"), `${JSON.stringify(manifest, null, 2)}\n`);
}

const ICONSET: [name: string, size: number][] = [
  ["icon_16x16", 16],
  ["icon_16x16@2x", 32],
  ["icon_32x32", 32],
  ["icon_32x32@2x", 64],
  ["icon_128x128", 128],
  ["icon_128x128@2x", 256],
  ["icon_256x256", 256],
  ["icon_256x256@2x", 512],
  ["icon_512x512", 512],
  ["icon_512x512@2x", 1024],
];

async function buildDesktopIcons() {
  copy(join(PNG, "compozy-app-icon-512.png"), join(DESKTOP_BUILD, "icon.png"));
  const winSizes = [16, 24, 32, 48, 64, 128, 256];
  const winImages = await Promise.all(
    winSizes.map(async size => ({ size, png: await resizePng(APP_ICON_SOURCE, size) }))
  );
  write(join(DESKTOP_BUILD, "icon.ico"), encodeIco(winImages));

  if (process.platform === "darwin") {
    const work = mkdtempSync(join(tmpdir(), "compozy-iconset-"));
    const iconset = join(work, "icon.iconset");
    mkdirSync(iconset);
    try {
      for (const [name, size] of ICONSET) {
        const png =
          size === 1024 ? readFileSync(APP_ICON_SOURCE) : await resizePng(APP_ICON_SOURCE, size);
        writeFileSync(join(iconset, `${name}.png`), png);
      }
      const icns = join(DESKTOP_BUILD, "icon.icns");
      execFileSync("iconutil", ["--convert", "icns", "--output", icns, iconset]);
      written.push(rel(icns));
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  } else {
    console.warn("skipped desktop/build/icon.icns: iconutil is macOS-only");
  }

  // Tray templates: macOS treats *Template.png as monochrome template images. No tray exists in
  // desktop/src yet, so these are staged next to the app icons for the tray feature to load.
  const trayOut = join(DESKTOP_BUILD, "tray");
  mkdirSync(trayOut, { recursive: true });
  for (const state of ["idle", "working", "attention"]) {
    for (const scale of ["", "@2x"]) {
      const name = `${state}Template${scale}.png`;
      const source = join(TRAY, `compozy-tray-${name}`);
      if (!existsSync(source)) throw new Error(`missing tray source ${rel(source)}`);
      copy(source, join(trayOut, name));
    }
  }
}

const assets = await buildUiModules();
await buildWebIcons(WEB_PUBLIC, assets.png64);
await buildWebIcons(SITE_PUBLIC, assets.png64);
buildLogoAssetModules(assets);
buildReadmeLockups();
await buildDesktopIcons();
execFileSync(
  "bunx",
  [
    "oxfmt",
    join(UI_CUSTOM, "logo-symbol.generated.ts"),
    join(UI_CUSTOM, "logo-wordmark.generated.ts"),
    ...LOGO_ASSET_MODULES,
  ],
  { cwd: ROOT, stdio: "inherit" }
);
console.log(`logos written:\n  ${written.join("\n  ")}`);
