CREATE TABLE forge_pull_requests (
 workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 repo_key TEXT NOT NULL CHECK (length(repo_key) > 0),
 branch TEXT NOT NULL CHECK (length(branch) > 0),
 provider TEXT NOT NULL DEFAULT '',
 pr_number INTEGER CHECK (pr_number IS NULL OR pr_number > 0),
 pr_url TEXT NOT NULL DEFAULT '',
 pr_state TEXT CHECK (pr_state IS NULL OR pr_state IN ('open', 'closed', 'merged')),
 merged INTEGER CHECK (merged IS NULL OR merged IN (0, 1)),
 draft INTEGER CHECK (draft IS NULL OR draft IN (0, 1)),
 head_sha TEXT NOT NULL DEFAULT '',
 base_ref TEXT NOT NULL DEFAULT '',
 checks_state TEXT NOT NULL DEFAULT 'unknown' CHECK (checks_state IN ('passing', 'failing', 'pending', 'none', 'unknown')),
 checks_passed INTEGER NOT NULL DEFAULT 0 CHECK (checks_passed >= 0),
 checks_failed INTEGER NOT NULL DEFAULT 0 CHECK (checks_failed >= 0),
 checks_pending INTEGER NOT NULL DEFAULT 0 CHECK (checks_pending >= 0),
 checks_failed_names TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(checks_failed_names)),
 review_decision TEXT NOT NULL DEFAULT 'unknown',
 mergeable TEXT NOT NULL DEFAULT 'unknown',
 pr_updated_at TEXT,
 observed_at TEXT,
 lookup_state TEXT NOT NULL DEFAULT 'pending' CHECK (lookup_state IN ('ok', 'pending', 'error', 'incomplete')),
 lookup_cause TEXT NOT NULL DEFAULT '',
 attempt_at TEXT,
 failure_count INTEGER NOT NULL DEFAULT 0 CHECK (failure_count >= 0),
 retry_after TEXT,
 PRIMARY KEY (workspace_id, repo_key, branch)
);
