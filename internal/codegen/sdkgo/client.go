package sdkgo

import (
	"fmt"
	"go/token"
	"reflect"
	"slices"
	"strings"
)

// ClientOperationKind selects the generated response transport.
type ClientOperationKind string

const (
	ClientOperationJSON ClientOperationKind = "json"
	ClientOperationSSE  ClientOperationKind = "sse"
)

const (
	clientParamInPath   = "path"
	clientParamInQuery  = "query"
	clientParamInHeader = "header"
)

// ClientParam describes a scalar HTTP parameter without depending on the API registry.
type ClientParam struct {
	Name     string
	In       string
	GoType   string
	GoName   string
	Required bool
	Enum     []string
}

// ClientOperation is the transport-neutral input to the public client generator.
type ClientOperation struct {
	ID                  string
	Method              string
	Path                string
	Kind                ClientOperationKind
	Params              []ClientParam
	RequestBody         any
	Response            any
	ResponseVariants    []any
	Summary             string
	Stability           string
	RequestContentType  string
	ResponseContentType string
}

// ClientType seeds a DTO used by a hand-written public operation.
type ClientType struct {
	Name  string
	Value any
}

// ClientOptions defines the generated package and the identifiers owned by its runtime.
type ClientOptions struct {
	PackageName string
	Header      string
	Reserved    []string
	Types       []ClientType
	// StringTypes identifies domain enums whose JSON wire representation is a string.
	StringTypes map[reflect.Type]bool
}

var clientRuntimeIdentifiers = []string{
	"New", "Prompt", "Do", "DaemonVersion", "Client", "Option", "PromptInput", "PromptChunk",
	"PromptStream", "Stream", "Frame", "APIError", "StreamError", "ConfigError", "UploadFile",
	"ErrUnavailable", "WithBaseURL", "WithSocket", "WithHome", "WithToken", "WithHTTPClient",
	"WithLogger", "WithClientID",
}

// ClientMethodName returns the public Go method for a registry operation id.
func ClientMethodName(operationID string) string { return exportIdentifier(operationID) }

// ClientParameterName returns the public Go field for an HTTP parameter wire name.
func ClientParameterName(wireName string) string { return clientParamIdentifier(wireName) }

// GenerateClient renders deterministic, stdlib-only client methods and DTOs.
func GenerateClient(operations []ClientOperation, opts ClientOptions) (Result, error) {
	if opts.PackageName == "" {
		opts.PackageName = "client"
	}
	if !token.IsIdentifier(opts.PackageName) || token.Lookup(opts.PackageName).IsKeyword() {
		return Result{}, fmt.Errorf("invalid client package name %q", opts.PackageName)
	}
	if opts.Header == "" {
		opts.Header = "Code generated by go run ./cmd/compozy-codegen sdk-client-go. DO NOT EDIT."
	}
	ops := slices.Clone(operations)
	slices.SortFunc(ops, func(a, b ClientOperation) int { return strings.Compare(a.ID, b.ID) })
	reserved := make(map[string]string)
	for _, name := range append(slices.Clone(clientRuntimeIdentifiers), opts.Reserved...) {
		reserved[name] = "reserved identifier"
	}
	if err := validateClientOperations(ops, reserved); err != nil {
		return Result{}, err
	}
	g := newTypeGenerator()
	g.allNamed = true
	g.stringTypes = opts.StringTypes
	for _, named := range opts.Types {
		if err := g.addClientRoot(named.Value, named.Name); err != nil {
			return Result{}, fmt.Errorf("client type %s: %w", named.Name, err)
		}
	}
	for _, op := range ops {
		roots := []ClientType{{Name: exportIdentifier(op.ID) + "Request", Value: op.RequestBody}}
		if clientJSONResponse(op) || op.Kind == ClientOperationSSE {
			roots = append(roots, ClientType{Name: exportIdentifier(op.ID) + "Response", Value: op.Response})
		}
		for index, variant := range op.ResponseVariants {
			roots = append(
				roots,
				ClientType{Name: fmt.Sprintf("%sVariant%d", exportIdentifier(op.ID), index+1), Value: variant},
			)
		}
		for _, root := range roots {
			if err := g.addClientRoot(root.Value, root.Name); err != nil {
				return Result{}, fmt.Errorf("operation %s: %w", op.ID, err)
			}
		}
	}
	files, err := renderClientFiles(g, ops, opts, reserved)
	if err != nil {
		return Result{}, err
	}
	return Result{Files: files}, nil
}

func validateClientOperations(ops []ClientOperation, reserved map[string]string) error {
	names := make(map[string]string)
	for _, op := range ops {
		name := exportIdentifier(op.ID)
		if op.ID == "" || !token.IsIdentifier(name) {
			return fmt.Errorf("invalid client operation identifier %q", op.ID)
		}
		if owner, exists := reserved[name]; exists {
			return fmt.Errorf("operation %s collides with %s %s", op.ID, owner, name)
		}
		if owner, exists := names[name]; exists {
			return fmt.Errorf("operation %s collides with operation %s at %s", op.ID, owner, name)
		}
		names[name] = op.ID
		if op.Kind != ClientOperationJSON && op.Kind != ClientOperationSSE {
			return fmt.Errorf("operation %s has unsupported kind %q", op.ID, op.Kind)
		}
		if !strings.HasPrefix(op.Path, "/") || op.Method == "" {
			return fmt.Errorf("operation %s requires an absolute path and HTTP method", op.ID)
		}
		if err := validateClientParams(op); err != nil {
			return err
		}
	}
	return nil
}

func validateClientParams(op ClientOperation) error {
	fields := make(map[string]string)
	path := op.Path
	for _, param := range op.Params {
		name := clientParameterField(param)
		if param.Name == "" || !token.IsIdentifier(name) {
			return fmt.Errorf("operation %s has invalid parameter %q", op.ID, param.Name)
		}
		if previous, exists := fields[name]; exists {
			return fmt.Errorf("operation %s parameters %s and %s collide at %s", op.ID, previous, param.Name, name)
		}
		fields[name] = param.Name
		switch param.GoType {
		case "string", "bool", "int", "int64":
		case "[]string":
			if param.In != clientParamInQuery {
				return fmt.Errorf(
					"operation %s parameter %s only supports string arrays in query parameters",
					op.ID,
					param.Name,
				)
			}
		default:
			return fmt.Errorf("operation %s parameter %s has unsupported Go type %q", op.ID, param.Name, param.GoType)
		}
		switch param.In {
		case clientParamInPath:
			placeholder := "{" + param.Name + "}"
			if !strings.Contains(path, placeholder) {
				return fmt.Errorf("operation %s path has no parameter %s", op.ID, param.Name)
			}
			path = strings.ReplaceAll(path, placeholder, "")
		case clientParamInQuery, clientParamInHeader:
		default:
			return fmt.Errorf("operation %s parameter %s has unsupported location %q", op.ID, param.Name, param.In)
		}
	}
	if strings.ContainsAny(path, "{}") {
		return fmt.Errorf("operation %s has undeclared path parameters in %s", op.ID, path)
	}
	return nil
}

func clientParamIdentifier(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '_' || r == '-' })
	for index, part := range parts {
		switch strings.ToLower(part) {
		case "id", "url", "http", "https", "api", "ip", "uuid":
			parts[index] = strings.ToUpper(part)
		default:
			parts[index] = exportIdentifier(part)
		}
	}
	return strings.Join(parts, "")
}

func clientParameterField(param ClientParam) string {
	if param.GoName != "" {
		return param.GoName
	}
	return clientParamIdentifier(param.Name)
}

func (g *typeGenerator) addClientRoot(value any, fallback string) error {
	if value == nil {
		return nil
	}
	// Generation reflects DTO structure once; generated clients contain no reflection or daemon imports.
	typ := reflect.TypeOf(value)
	if err := validateClientType(typ, make(map[reflect.Type]bool)); err != nil {
		return err
	}
	for typ.Kind() == reflect.Pointer {
		typ = typ.Elem()
	}
	if typ == rawMessageType || typ == timeType || typ == durationType {
		return nil
	}
	if typ.PkgPath() == "" && typ.Kind() != reflect.Struct {
		return nil
	}
	if _, exists := g.preferred[typ]; exists {
		return nil
	}
	name := typ.Name()
	if name == "" {
		if typ.Kind() != reflect.Struct {
			return nil
		}
		name = fallback
	}
	if existing, exists := g.declarations[name]; exists && existing != typ {
		name = g.uniqueGeneratedName(typ)
	}
	g.declarations[name] = typ
	g.preferred[typ] = name
	return nil
}

func validateClientType(typ reflect.Type, visited map[reflect.Type]bool) error {
	if visited[typ] || typ == timeType || typ == rawMessageType || typ == durationType {
		return nil
	}
	visited[typ] = true
	if strings.ContainsAny(typ.Name(), "[]") {
		return fmt.Errorf("generic instantiation %s requires a named non-generic DTO", typ)
	}
	switch typ.Kind() {
	case reflect.Pointer, reflect.Slice, reflect.Array:
		return validateClientType(typ.Elem(), visited)
	case reflect.Map:
		if err := validateClientType(typ.Key(), visited); err != nil {
			return err
		}
		return validateClientType(typ.Elem(), visited)
	case reflect.Struct:
		for field := range typ.Fields() {
			if field.IsExported() && field.Tag.Get("json") != "-" {
				if err := validateClientType(field.Type, visited); err != nil {
					return err
				}
			}
		}
	case reflect.Chan, reflect.Func, reflect.UnsafePointer, reflect.Complex64, reflect.Complex128:
		return fmt.Errorf("type %s cannot be represented in a JSON client", typ)
	}
	return nil
}
