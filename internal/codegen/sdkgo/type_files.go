package sdkgo

import (
	"bytes"
	"fmt"
	"sort"

	"github.com/dave/jennifer/jen"
)

const generatedTypesPerFile = 24

func (g *typeGenerator) renderFiles() (map[string][]byte, error) {
	if err := g.renderAll(); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(g.rendered))
	for name := range g.rendered {
		names = append(names, name)
	}
	sort.Strings(names)

	files := make(map[string][]byte, (len(names)+generatedTypesPerFile-1)/generatedTypesPerFile)
	for start := 0; start < len(names); start += generatedTypesPerFile {
		end := min(start+generatedTypesPerFile, len(names))
		file := newGeneratedFile()
		for _, name := range names[start:end] {
			file.Add(g.rendered[name])
			file.Line()
		}
		content, err := renderJenniferFile(file)
		if err != nil {
			return nil, fmt.Errorf("render generated type chunk %d: %w", start/generatedTypesPerFile+1, err)
		}
		files[fmt.Sprintf("types_%03d_gen.go", start/generatedTypesPerFile+1)] = content
	}
	return files, nil
}

func newGeneratedFile() *jen.File {
	file := jen.NewFile("contracts")
	file.HeaderComment("Code generated by go run ./cmd/compozy-codegen sdk-contracts-go. DO NOT EDIT.")
	return file
}

func renderJenniferFile(file *jen.File) ([]byte, error) {
	var output bytes.Buffer
	if err := file.Render(&output); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}
