package hostapi

import (
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"
)

const generatedHeader = "// Code generated by go run ./cmd/compozy-codegen host-api. DO NOT EDIT.\n\n"

const (
	ProtocolPath = "internal/extensionprotocol/host_api_methods_gen.go"
	AliasesPath  = "internal/extension/contract/host_api_method_aliases_gen.go"
	RegistryPath = "internal/extension/contract/host_api_method_registry_gen.go"
)

var importPaths = map[string]string{
	"apicontract":   "github.com/compozy/compozy/internal/api/contract",
	"automationpkg": "github.com/compozy/compozy/internal/automation",
	"bridgepkg":     "github.com/compozy/compozy/internal/bridges/contract",
	"toolspkg":      "github.com/compozy/compozy/internal/tools",
}

// Result is the complete deterministic internal Host API generated file set.
type Result struct {
	Files       map[string][]byte
	MethodCount int
}

// Generate renders all protocol and typed-registry projections from the catalog.
func Generate() (Result, error) {
	methods, err := loadCatalog()
	if err != nil {
		return Result{}, err
	}
	files := make(map[string][]byte, len(familyOrder)+3)
	protocol, err := renderProtocol(methods)
	if err != nil {
		return Result{}, err
	}
	files[ProtocolPath] = protocol
	aliases, err := renderAliases(methods)
	if err != nil {
		return Result{}, err
	}
	files[AliasesPath] = aliases
	for _, family := range familyOrder {
		familyMethods := methodsForFamily(methods, family)
		content, renderErr := renderRegistryFamily(family, familyMethods)
		if renderErr != nil {
			return Result{}, renderErr
		}
		files[registryFamilyPath(family)] = content
	}
	registry, err := renderRegistry()
	if err != nil {
		return Result{}, err
	}
	files[RegistryPath] = registry
	return Result{Files: files, MethodCount: len(methods)}, nil
}

// FileNames returns generated paths in deterministic order.
func (r Result) FileNames() []string {
	names := slices.Collect(maps.Keys(r.Files))
	slices.Sort(names)
	return names
}

func renderProtocol(methods []method) ([]byte, error) {
	var source strings.Builder
	source.WriteString(generatedHeader)
	source.WriteString("package protocol\n\nconst (\n")
	for _, entry := range methods {
		fmt.Fprintf(&source, "\t%s HostAPIMethod = %q\n", entry.Constant, entry.Wire)
	}
	source.WriteString(")\n\nvar allHostAPIMethods = []HostAPIMethod{\n")
	for _, entry := range methods {
		fmt.Fprintf(&source, "\t%s,\n", entry.Constant)
	}
	source.WriteString("}\n\n")
	source.WriteString("// AllHostAPIMethods returns the canonical Host API method registry in wire order.\n")
	source.WriteString("func AllHostAPIMethods() []HostAPIMethod {\n")
	source.WriteString("\treturn append([]HostAPIMethod(nil), allHostAPIMethods...)\n}\n")
	return formatSource(ProtocolPath, source.String())
}

func renderAliases(methods []method) ([]byte, error) {
	var source strings.Builder
	source.WriteString(generatedHeader)
	source.WriteString("package contract\n\n")
	source.WriteString("import extensionprotocol \"github.com/compozy/compozy/internal/extensionprotocol\"\n\n")
	source.WriteString("const (\n")
	for _, entry := range methods {
		fmt.Fprintf(&source, "\t%s = extensionprotocol.%s\n", entry.Constant, entry.Constant)
	}
	source.WriteString(")\n")
	return formatSource(AliasesPath, source.String())
}

func renderRegistryFamily(family string, methods []method) ([]byte, error) {
	path := registryFamilyPath(family)
	var source strings.Builder
	source.WriteString(generatedHeader)
	source.WriteString("package contract\n")
	imports := importsForMethods(methods)
	if len(imports) > 0 {
		source.WriteString("\nimport (\n")
		for _, alias := range imports {
			fmt.Fprintf(&source, "\t%s %q\n", alias, importPaths[alias])
		}
		source.WriteString(")\n")
	}
	fmt.Fprintf(&source, "\nvar hostAPIMethodSpecs%s = []HostAPIMethodSpec{\n", familyIdentifier(family))
	for _, entry := range methods {
		renderMethodSpec(&source, entry)
	}
	source.WriteString("}\n")
	return formatSource(path, source.String())
}

func renderMethodSpec(source *strings.Builder, entry method) {
	source.WriteString("\t{\n")
	fmt.Fprintf(source, "\t\tMethod: HostAPIMethod(%q),\n", entry.Wire)
	fmt.Fprintf(source, "\t\tParams: NamedType{Name: %q, Value: %s},\n", entry.Params.Name, entry.Params.Value)
	fmt.Fprintf(source, "\t\tResult: NamedType{Name: %q, Value: %s},\n", entry.Result.Name, entry.Result.Value)
	if entry.OptionalParams {
		source.WriteString("\t\tOptionalParams: true,\n")
	}
	source.WriteString("\t},\n")
}

func renderRegistry() ([]byte, error) {
	var source strings.Builder
	source.WriteString(generatedHeader)
	source.WriteString("package contract\n\n")
	source.WriteString("var hostAPIMethodSpecGroups = [][]HostAPIMethodSpec{\n")
	for _, family := range familyOrder {
		fmt.Fprintf(&source, "\thostAPIMethodSpecs%s,\n", familyIdentifier(family))
	}
	source.WriteString("}\n\n")
	source.WriteString("// HostAPIMethodSpecs returns the canonical Host API method registry in wire order.\n")
	source.WriteString("func HostAPIMethodSpecs() []HostAPIMethodSpec {\n")
	source.WriteString("\ttotal := 0\n")
	source.WriteString("\tfor _, group := range hostAPIMethodSpecGroups { total += len(group) }\n")
	source.WriteString("\tspecs := make([]HostAPIMethodSpec, 0, total)\n")
	source.WriteString("\tfor _, group := range hostAPIMethodSpecGroups { specs = append(specs, group...) }\n")
	source.WriteString("\treturn specs\n}\n")
	return formatSource(RegistryPath, source.String())
}

func methodsForFamily(methods []method, family string) []method {
	selected := make([]method, 0)
	for _, entry := range methods {
		if entry.Family == family {
			selected = append(selected, entry)
		}
	}
	return selected
}

func importsForMethods(methods []method) []string {
	aliases := make([]string, 0, len(importPaths))
	for alias := range importPaths {
		needle := alias + "."
		for _, entry := range methods {
			if strings.Contains(entry.Params.Value, needle) || strings.Contains(entry.Result.Value, needle) {
				aliases = append(aliases, alias)
				break
			}
		}
	}
	slices.Sort(aliases)
	return aliases
}

func registryFamilyPath(family string) string {
	return "internal/extension/contract/host_api_method_registry_" +
		strings.ReplaceAll(family, "-", "_") + "_gen.go"
}

func familyIdentifier(family string) string {
	return strings.ToUpper(family[:1]) + family[1:]
}

func formatSource(path string, source string) ([]byte, error) {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("format generated Host API file %q: %w", path, err)
	}
	return formatted, nil
}
