package spec

// Suite: Operation registry defensive copies and response schema descriptors.
// Invariant: Returned operations cannot expose mutable response-schema storage.
// Boundary IN: Registry cloning and the OpenAPI response-schema builder.
// Boundary OUT: HTTP/UDS handlers, which consume the generated contract.

import (
	"bytes"
	"encoding/json"
	"reflect"
	"slices"
	"testing"

	"github.com/compozy/compozy/internal/api/contract"
	"github.com/getkin/kin-openapi/openapi3"
)

func TestOperationsReturnDefensiveCopies(t *testing.T) {
	t.Parallel()

	t.Run("Should isolate operation slices from registry mutations", func(t *testing.T) {
		t.Parallel()

		const (
			path   = "/api/automation/jobs"
			method = "GET"
		)
		operations := Operations()
		operation := operationSpecFor(t, operations, path, method)
		paramIndex := firstParameterWithEnum(t, operation)
		wantTag := operation.Tags[0]
		wantTransport := operation.Transports[0]
		wantParamName := operation.Parameters[paramIndex].Name
		wantParamEnum := operation.Parameters[paramIndex].Enum[0]
		wantResponseStatus := operation.Responses[0].Status

		operation.Tags[0] = "mutated-tag"
		operation.Transports[0] = Transport("mutated-transport")
		operation.Parameters[paramIndex].Name = "mutated-param"
		operation.Parameters[paramIndex].Enum[0] = "mutated-enum"
		operation.Responses[0].Status = 599

		fresh := operationSpecFor(t, Operations(), path, method)
		if got := fresh.Tags[0]; got != wantTag {
			t.Fatalf("Tags[0] = %q, want %q", got, wantTag)
		}
		if got := fresh.Transports[0]; got != wantTransport {
			t.Fatalf("Transports[0] = %q, want %q", got, wantTransport)
		}
		if got := fresh.Parameters[paramIndex].Name; got != wantParamName {
			t.Fatalf("Parameters[%d].Name = %q, want %q", paramIndex, got, wantParamName)
		}
		if got := fresh.Parameters[paramIndex].Enum[0]; got != wantParamEnum {
			t.Fatalf("Parameters[%d].Enum[0] = %q, want %q", paramIndex, got, wantParamEnum)
		}
		if got := fresh.Responses[0].Status; got != wantResponseStatus {
			t.Fatalf("Responses[0].Status = %d, want %d", got, wantResponseStatus)
		}
	})

	t.Run("Should isolate request body maps from registry mutations", func(t *testing.T) {
		t.Parallel()

		const (
			path       = "/api/webhooks/global/{endpoint}"
			method     = "POST"
			mutatedKey = "mutated"
		)
		operation := operationSpecFor(t, Operations(), path, method)
		body, ok := operation.RequestBody.(map[string]any)
		if !ok {
			t.Fatalf("RequestBody = %T, want map[string]any", operation.RequestBody)
		}

		body[mutatedKey] = "value"

		fresh := operationSpecFor(t, Operations(), path, method)
		freshBody, ok := fresh.RequestBody.(map[string]any)
		if !ok {
			t.Fatalf("fresh RequestBody = %T, want map[string]any", fresh.RequestBody)
		}
		if _, ok := freshBody[mutatedKey]; ok {
			t.Fatalf("fresh RequestBody contains %q after mutating returned copy", mutatedKey)
		}
	})

	t.Run("Should clone response body descriptor backing storage", func(t *testing.T) {
		t.Parallel()

		original := []ResponseSpec{
			{Bodies: responseBodiesOf(responseBodyOf[contract.ErrorPayload]())},
		}
		cloned := cloneResponseSpecs(original)
		cloned[0].Bodies.schemaTypes[0] = reflect.TypeFor[contract.SendPromptResultResponse]()

		if got, want := original[0].Bodies.schemaTypes[0], reflect.TypeFor[contract.ErrorPayload](); got != want {
			t.Fatalf("original response descriptor type = %v, want %v", got, want)
		}
	})

	t.Run("Should isolate transport authentication maps from registry mutations", func(t *testing.T) {
		t.Parallel()

		const (
			path      = "/api/gateway/status"
			method    = "GET"
			transport = TransportHTTP
		)
		operation := operationSpecFor(t, Operations(), path, method)
		wantAuth := operation.Auth[transport]
		operation.Auth[transport] = OperationAuth("mutated-auth")

		fresh := operationSpecFor(t, Operations(), path, method)
		if got := fresh.Auth[transport]; got != wantAuth {
			t.Fatalf("Auth[%q] = %q, want %q", transport, got, wantAuth)
		}
	})
}

func TestResponseBodyDescriptors(t *testing.T) {
	t.Run("Should preserve the response union generated by concrete body values", func(t *testing.T) {
		t.Parallel()

		actual := responseSchemaFor(t, promptGoalErrorResponse(422, "Goal turn filter is invalid"))
		if actual.Value == nil {
			t.Fatal("response schema is nil")
		}
		if got, want := len(actual.Value.OneOf), 2; got != want {
			t.Fatalf("response union branches = %d, want %d", got, want)
		}

		expectedSchemas := openapi3.Schemas{}
		expectedError, err := schemaRefForValue(contract.ErrorPayload{}, expectedSchemas)
		if err != nil {
			t.Fatalf("schemaRefForValue(ErrorPayload) error = %v", err)
		}
		expectedPrompt, err := schemaRefForValue(contract.SendPromptResultResponse{}, expectedSchemas)
		if err != nil {
			t.Fatalf("schemaRefForValue(SendPromptResultResponse) error = %v", err)
		}
		want := []*openapi3.SchemaRef{expectedError, expectedPrompt}
		gotJSON, err := json.Marshal(actual.Value.OneOf)
		if err != nil {
			t.Fatalf("marshal response union = %v", err)
		}
		wantJSON, err := json.Marshal(want)
		if err != nil {
			t.Fatalf("marshal expected response union = %v", err)
		}
		if !bytes.Equal(gotJSON, wantJSON) {
			t.Fatal("response union differs from the concrete body schemas")
		}
	})

	t.Run("Should express map and slice body types", func(t *testing.T) {
		t.Parallel()

		type item struct {
			ID string `json:"id"`
		}
		response := ResponseSpec{
			Status:      200,
			Description: "OK",
			Bodies: responseBodiesOf(
				responseBodyOf[map[string]item](),
				responseBodyOf[[]item](),
			),
		}
		schema := responseSchemaFor(t, response)
		if schema.Value == nil {
			t.Fatal("response schema is nil")
		}
		if got, want := len(schema.Value.OneOf), 2; got != want {
			t.Fatalf("response union branches = %d, want %d", got, want)
		}
		assertSchemaType(t, schema.Value.OneOf[0], "object")
		assertSchemaType(t, schema.Value.OneOf[1], "array")
	})

	t.Run("Should render typed body descriptors as valid OpenAPI", func(t *testing.T) {
		t.Parallel()

		rendered, err := Render()
		if err != nil {
			t.Fatalf("Render() error = %v", err)
		}
		if !json.Valid(rendered) {
			t.Fatalf("Render() output is not valid JSON: %s", string(rendered))
		}
	})
}

func responseSchemaFor(t *testing.T, response ResponseSpec) *openapi3.SchemaRef {
	t.Helper()

	built, err := buildResponse(openapi3.Schemas{}, response)
	if err != nil {
		t.Fatalf("buildResponse() error = %v", err)
	}
	content, ok := built.Content["application/json"]
	if !ok {
		t.Fatal("response content is missing application/json")
	}
	return content.Schema
}

func assertSchemaType(t *testing.T, schema *openapi3.SchemaRef, want string) {
	t.Helper()

	if schema == nil || schema.Value == nil || schema.Value.Type == nil {
		t.Fatalf("schema = %#v, want type %q", schema, want)
	}
	if slices.Contains(*schema.Value.Type, want) {
		return
	}
	t.Fatalf("schema types = %v, want %q", *schema.Value.Type, want)
}

func operationSpecFor(t *testing.T, operations []OperationSpec, path string, method string) OperationSpec {
	t.Helper()

	for _, operation := range operations {
		if operation.Path == path && operation.Method == method {
			return operation
		}
	}
	t.Fatalf("missing operation %s %s", method, path)
	return OperationSpec{}
}

func firstParameterWithEnum(t *testing.T, operation OperationSpec) int {
	t.Helper()

	for index, parameter := range operation.Parameters {
		if len(parameter.Enum) > 0 {
			return index
		}
	}
	t.Fatalf("operation %s %s has no enum parameter", operation.Method, operation.Path)
	return 0
}
