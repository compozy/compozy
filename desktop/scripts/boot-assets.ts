// Static assets of the boot page, written next to its HTML at build time. The page is CSP-locked to
// self-hosted files, so the brand mark, the Atmosphere visual, the fonts and the agents' faces ship
// as files instead of being fetched or generated at runtime.
import { copyFile, mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";

import { blobatar } from "blobatar";
import { sad, sleepy, thinking } from "blobatar/expression";

import { AGENT_AVATAR_TONES } from "../../packages/ui/src/lib/agent-avatar-tones";
import { RUNNER_AGENTS, type RunnerMood } from "../src/boot/page/runner-engine";

const require = createRequire(import.meta.url);

/** The product's AgentAvatar poses for the states the runner wears. */
const POSES: Record<RunnerMood, typeof thinking> = {
  working: thinking,
  failed: sad,
  paused: sleepy,
};

const FONTS = [
  ["Figtree Variable", "@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2"],
  [
    "Instrument Sans Variable",
    "@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2",
  ],
  [
    "Geist Mono Variable",
    "@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2",
  ],
] as const;

async function writeFaces(pages: string): Promise<void> {
  const faces = join(pages, "assets", "faces");
  await mkdir(faces, { recursive: true });
  const tones = AGENT_AVATAR_TONES[1];
  const writes = RUNNER_AGENTS.flatMap(agent =>
    (Object.keys(POSES) as RunnerMood[]).flatMap(mood =>
      (["dark", "light"] as const).map(theme =>
        writeFile(
          join(faces, `${agent}-${mood}-${theme}.svg`),
          blobatar(agent, {
            expression: POSES[mood],
            traits: { tone: [...tones[theme]] },
            background: false,
          }),
          "utf8"
        )
      )
    )
  );
  await Promise.all(writes);
}

async function writeFonts(pages: string): Promise<void> {
  const fonts = join(pages, "fonts");
  await mkdir(fonts, { recursive: true });
  const faces = await Promise.all(
    FONTS.map(async ([family, source]) => {
      const file = source.slice(source.lastIndexOf("/") + 1);
      await copyFile(require.resolve(source), join(fonts, file));
      return (
        `@font-face {\n  font-family: "${family}";\n  font-style: normal;\n` +
        `  font-weight: 100 900;\n  font-display: swap;\n  src: url("fonts/${file}") format("woff2");\n}\n`
      );
    })
  );
  await writeFile(
    join(pages, "boot-fonts.css"),
    `/* Generated by scripts/boot-assets.ts: the product's self-hosted faces, latin subset. */\n${faces.join("")}`,
    "utf8"
  );
}

export async function writeBootAssets(root: string, pages: string): Promise<void> {
  const brand = join(root, "..", "packages", "brand", "public", "brand");
  const assets = join(pages, "assets");
  await mkdir(assets, { recursive: true });
  await Promise.all([
    copyFile(join(brand, "png", "compozy-symbol-192.png"), join(assets, "symbol.png")),
    // Atmosphere `horizon`: the one visual the brand allows inside a product window (≤ 25%).
    copyFile(join(brand, "visuals", "horizon-1280.jpg"), join(assets, "horizon.jpg")),
    writeFaces(pages),
    writeFonts(pages),
  ]);
}
