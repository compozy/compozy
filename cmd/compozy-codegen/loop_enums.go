package main

import (
	"context"
	"fmt"
	"strings"

	"github.com/compozy/compozy/internal/api/contract"
)

func writeLoopEnums(ctx context.Context, path string) error {
	content, err := generateFormattedLoopEnums(ctx, path)
	if err != nil {
		return err
	}
	if err := publishGeneratedFile(path, content); err != nil {
		return fmt.Errorf("write loop enums to %q: %w", path, err)
	}
	return nil
}

func checkLoopEnums(ctx context.Context, path string) error {
	content, err := generateFormattedLoopEnums(ctx, path)
	if err != nil {
		return err
	}
	return checkFile(path, content)
}

func generateFormattedLoopEnums(ctx context.Context, path string) ([]byte, error) {
	content := generateLoopEnumsTS()
	formatted, err := formatTypeScript(ctx, path, content)
	if err != nil {
		return nil, err
	}
	return formatted, nil
}

func generateLoopEnumsTS() []byte {
	var out strings.Builder
	out.WriteString("// Code generated by go run ./cmd/compozy-codegen loop-enums. DO NOT EDIT.\n\n")
	writeTSExportedConstArray(&out, "LOOP_RUN_STATUSES", contract.LoopRunStatusValues())
	out.WriteString("export type LoopRunStatusValue = (typeof LOOP_RUN_STATUSES)[number];\n\n")
	writeTSExportedConstArray(&out, "LOOP_RUN_LIVE_STATUSES", contract.LoopRunLiveStatusValues())
	out.WriteString("\n")
	writeTSExportedConstArray(&out, "LOOP_RUN_TERMINAL_STATUSES", contract.LoopRunTerminalStatusValues())
	out.WriteString("\n")
	writeTSExportedConstArray(&out, "LOOP_RUN_EVENT_KINDS", contract.LoopRunEventKindValues())
	out.WriteString("export type LoopRunEventKindValue = (typeof LOOP_RUN_EVENT_KINDS)[number];\n\n")
	writeTSConstArray(&out, "LOOP_GENERATION_ORIGINS", contract.LoopGenerationOriginValues())
	out.WriteString("export type LoopGenerationOriginValue = (typeof LOOP_GENERATION_ORIGINS)[number];\n\n")
	writeTSConstArray(&out, "LOOP_GATE_VERDICT_OUTCOMES", contract.LoopGateVerdictOutcomeValues())
	out.WriteString("export type LoopGateVerdictOutcomeValue = (typeof LOOP_GATE_VERDICT_OUTCOMES)[number];\n\n")
	writeTSConstArray(&out, "LOOP_METRIC_DIRECTIONS", contract.LoopMetricDirectionValues())
	out.WriteString("export type LoopMetricDirectionValue = (typeof LOOP_METRIC_DIRECTIONS)[number];\n\n")
	writeTSExportedConstArray(&out, "LOOP_RUN_LIFECYCLE_EVENT_KINDS", contract.LoopRunLifecycleEventKindValues())
	out.WriteString("\n")
	writeTSExportedConstArray(&out, "LOOP_WATCH_EVENT_KINDS", contract.LoopWatchEventKindValues())
	out.WriteString("export type LoopWatchEventKindValue = (typeof LOOP_WATCH_EVENT_KINDS)[number];\n")
	return []byte(out.String())
}

func writeTSExportedConstArray(out *strings.Builder, name string, values []string) {
	out.WriteString("export ")
	writeTSConstArray(out, name, values)
}

func writeTSConstArray(out *strings.Builder, name string, values []string) {
	out.WriteString("const ")
	out.WriteString(name)
	out.WriteString(" = [\n")
	for _, value := range values {
		out.WriteString("  ")
		fmt.Fprintf(out, "%q", value)
		out.WriteString(",\n")
	}
	out.WriteString("] as const;\n\n")
}
