func assertGeneratedArtifactsEqual(t *testing.T, expected map[string][]byte) {
	t.Helper()
	for path, want := range expected {
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("os.ReadFile(%q) error = %v", path, err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("artifact %q after rollback = %q, want %q", path, got, want)
		}
	}
}

func assertGeneratedTreeEqual(t *testing.T, path string, expected map[string][]byte) {
	t.Helper()
	actual := make(map[string][]byte)
	err := filepath.WalkDir(path, func(file string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		name, err := filepath.Rel(path, file)
		if err != nil {
			return err
		}
		content, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		actual[filepath.ToSlash(name)] = content
		return nil
	})
	if err != nil {
		t.Fatalf("read generated tree %q: %v", path, err)
	}
	if len(actual) != len(expected) {
		t.Fatalf("generated tree files = %d, want %d", len(actual), len(expected))
	}
	for name, want := range expected {
		got, exists := actual[name]
		if !exists || !bytes.Equal(got, want) {
			t.Fatalf("generated tree file %q = %q, want %q", name, got, want)
		}
	}
}

