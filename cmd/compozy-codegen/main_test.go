func TestCheckJSONFile(t *testing.T) {
	tests := []struct {
		name        string
		fileContent []byte
		want        []byte
		wantErr     error
	}{
		{
			name:        "ShouldIgnoreFormattingDifferences",
			fileContent: []byte("{\n  \"z\": 1,\n  \"nested\": {\"b\": 2, \"a\": [1, 2]}\n}\n"),
			want:        []byte("{\"nested\":{\"a\":[1,2],\"b\":2},\"z\":1}"),
		},
		{
			name:        "ShouldRejectContentDifferences",
			fileContent: []byte("{\"version\":1}\n"),
			want:        []byte("{\"version\":2}\n"),
			wantErr:     ErrStaleGeneratedFile,
		},
		{
			name:        "ShouldIgnoreEquivalentNumberRepresentations",
			fileContent: []byte("{\"version\":1.0}\n"),
			want:        []byte("{\"version\":1}\n"),
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			path := filepath.Join(t.TempDir(), "openapi.json")
			if err := os.WriteFile(path, tt.fileContent, 0o644); err != nil {
				t.Fatalf("os.WriteFile() error = %v", err)
			}

			err := checkJSONFile(path, tt.want)
			switch {
			case tt.wantErr == nil && err != nil:
				t.Fatalf("checkJSONFile() error = %v, want nil", err)
			case tt.wantErr != nil && !errors.Is(err, tt.wantErr):
				t.Fatalf("checkJSONFile() error = %v, want %v", err, tt.wantErr)
			}
		})
	}

	t.Run("ShouldReportMissingFiles", func(t *testing.T) {
		t.Parallel()

		path := filepath.Join(t.TempDir(), "missing-openapi.json")
		err := checkJSONFile(path, []byte("{}"))
		if err == nil {
			t.Fatal("checkJSONFile() error = nil, want missing file error")
		}
		if !strings.Contains(err.Error(), "missing; run codegen") {
			t.Fatalf("checkJSONFile() error = %q, want missing output guidance", err.Error())
		}
	})

	t.Run("ShouldRejectInvalidCheckedInJSON", func(t *testing.T) {
		t.Parallel()

		path := filepath.Join(t.TempDir(), "openapi.json")
		if err := os.WriteFile(path, []byte("{broken"), 0o644); err != nil {
			t.Fatalf("os.WriteFile() error = %v", err)
		}

		err := checkJSONFile(path, []byte("{}"))
		if err == nil {
			t.Fatal("checkJSONFile() error = nil, want decode error")
		}
		if !strings.Contains(err.Error(), "decode") {
			t.Fatalf("checkJSONFile() error = %q, want decode context", err.Error())
		}
	})

	t.Run("ShouldRejectInvalidGeneratedJSON", func(t *testing.T) {
		t.Parallel()

		path := filepath.Join(t.TempDir(), "openapi.json")
		if err := os.WriteFile(path, []byte("{}"), 0o644); err != nil {
			t.Fatalf("os.WriteFile() error = %v", err)
		}

		err := checkJSONFile(path, []byte("{broken"))
		if err == nil {
			t.Fatal("checkJSONFile() error = nil, want decode error")
		}
		if !strings.Contains(err.Error(), "decode generated json") {
			t.Fatalf("checkJSONFile() error = %q, want generated decode context", err.Error())
		}
	})
}

