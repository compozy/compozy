func TestRunWithPaths(t *testing.T) {
	t.Run("ShouldReturnUsageWhenTargetIsMissing", func(t *testing.T) {
		t.Parallel()

		err := runWithPaths(context.Background(), nil, "ignored-openapi.json", "ignored-contracts.ts")
		if err == nil {
			t.Fatal("runWithPaths() error = nil, want usage error")
		}
		if !strings.Contains(err.Error(), "usage: compozy-codegen") {
			t.Fatalf("runWithPaths() error = %q, want usage guidance", err.Error())
		}
	})

	t.Run("ShouldRejectUnknownTargets", func(t *testing.T) {
		t.Parallel()

		err := runWithPaths(
			context.Background(),
			[]string{"unknown"},
			"ignored-openapi.json",
			"ignored-contracts.ts",
		)
		if err == nil {
			t.Fatal("runWithPaths() error = nil, want unknown target error")
		}
		if !strings.Contains(err.Error(), `unknown codegen target "unknown"`) {
			t.Fatalf("runWithPaths() error = %q, want unknown target guidance", err.Error())
		}
	})

	t.Run("ShouldWriteAndCheckOpenAPIAtProvidedPath", func(t *testing.T) {
		t.Parallel()

		openapiPath := filepath.Join(t.TempDir(), "generated", "compozy.json")

		if err := runWithPaths(
			context.Background(),
			[]string{"openapi"},
			openapiPath,
			"ignored-contracts.ts",
		); err != nil {
			t.Fatalf("runWithPaths(openapi) error = %v", err)
		}

		content, err := os.ReadFile(openapiPath)
		if err != nil {
			t.Fatalf("os.ReadFile(%q) error = %v", openapiPath, err)
		}
		if !bytes.Contains(content, []byte(`"openapi": "3.0.3"`)) {
			t.Fatalf("generated openapi missing version header: %s", string(content))
		}

		if err := runWithPaths(
			context.Background(),
			[]string{"check"},
			openapiPath,
			filepath.Join(t.TempDir(), "missing.ts"),
		); err == nil {
			t.Fatal("runWithPaths(check) error = nil, want sdk missing output error")
		} else if !strings.Contains(
			err.Error(),
			"missing; run codegen",
		) {
			t.Fatalf("runWithPaths(check) error = %q, want missing output guidance", err.Error())
		}

		if err := checkOpenAPI(openapiPath); err != nil {
			t.Fatalf("checkOpenAPI() error = %v", err)
		}
	})

	t.Run("ShouldWriteAndCheckSDKContractsAtProvidedPath", func(t *testing.T) {
		t.Parallel()

		sdkContractsPath := filepath.Join(t.TempDir(), "sdk", "contracts.ts")

		if err := runWithPaths(
			context.Background(),
			[]string{"sdk-contracts"},
			"ignored-openapi.json",
			sdkContractsPath,
		); err != nil {
			t.Fatalf("runWithPaths(sdk-contracts) error = %v", err)
		}

		content, err := os.ReadFile(sdkContractsPath)
		if err != nil {
			t.Fatalf("os.ReadFile(%q) error = %v", sdkContractsPath, err)
		}
		if !bytes.Contains(content, []byte("Code generated by go run ./cmd/compozy-codegen sdk-contracts")) {
			t.Fatalf("generated sdk contracts missing header: %s", string(content))
		}

		if err := checkSDKContracts(context.Background(), sdkContractsPath); err != nil {
			t.Fatalf("checkSDKContracts() error = %v", err)
		}
	})

	t.Run("Should generate both terminal wire languages from one manifest", func(t *testing.T) {
		t.Parallel()
		directory := t.TempDir()
		paths := terminalWirePaths{
			goOutput:   filepath.Join(directory, "opcodes_generated.go"),
			tsOutput:   filepath.Join(directory, "terminal-wire.ts"),
			docsOutput: filepath.Join(directory, "terminal-wire.md"),
		}
		if err := writeTerminalWire(t.Context(), paths); err != nil {
			t.Fatalf("writeTerminalWire() error = %v", err)
		}
		if err := checkTerminalWire(t.Context(), paths); err != nil {
			t.Fatalf("checkTerminalWire() error = %v", err)
		}
		goContent, err := os.ReadFile(paths.goOutput)
		if err != nil {
			t.Fatalf("ReadFile(Go terminal wire) error = %v", err)
		}
		tsContent, err := os.ReadFile(paths.tsOutput)
		if err != nil {
			t.Fatalf("ReadFile(TypeScript terminal wire) error = %v", err)
		}
		for _, contract := range [][]byte{goContent, tsContent} {
			if !bytes.Contains(contract, []byte("compozy.terminal.v2")) ||
				!bytes.Contains(contract, []byte("RedactedInput")) &&
					!bytes.Contains(contract, []byte("redactedInput")) {
				t.Fatalf("generated terminal wire contract is incomplete: %s", contract)
			}
		}
		if err := os.WriteFile(paths.tsOutput, []byte("export const stale = true;\n"), 0o600); err != nil {
			t.Fatalf("WriteFile(stale terminal wire) error = %v", err)
		}
		if err := checkTerminalWire(t.Context(), paths); !errors.Is(err, ErrStaleGeneratedFile) {
			t.Fatalf("checkTerminalWire(stale) error = %v, want ErrStaleGeneratedFile", err)
		}
	})

	t.Run("Should require a version bump for incompatible terminal wire edits", func(t *testing.T) {
		t.Parallel()

		manifestPath := filepath.Join("..", "..", defaultTerminalWireManifestPath)
		manifest, err := readTerminalWireManifest(manifestPath)
		if err != nil {
			t.Fatalf("readTerminalWireManifest() error = %v", err)
		}
		mutations := map[string]func(*terminalWireManifest){
			"rename": func(candidate *terminalWireManifest) {
				candidate.Server[0].GoName = "ServerOpRenamed"
			},
			"remove": func(candidate *terminalWireManifest) {
				candidate.Server = candidate.Server[:len(candidate.Server)-1]
			},
			"add": func(candidate *terminalWireManifest) {
				candidate.Server = append(candidate.Server, terminalWireOpcode{
					GoName: "ServerOpAdded", TSName: "added", Value: byte(len(candidate.Server) + 1),
				})
			},
		}
		for name, mutate := range mutations {
			t.Run("Should reject terminal wire "+name+" without a version bump", func(t *testing.T) {
				t.Parallel()

				encoded, marshalErr := json.Marshal(manifest)
				if marshalErr != nil {
					t.Fatalf("json.Marshal(manifest) error = %v", marshalErr)
				}
				var candidate terminalWireManifest
				if unmarshalErr := json.Unmarshal(encoded, &candidate); unmarshalErr != nil {
					t.Fatalf("json.Unmarshal(manifest) error = %v", unmarshalErr)
				}
				mutate(&candidate)
				if validationErr := validateTerminalWireManifest(candidate); validationErr == nil ||
					!strings.Contains(validationErr.Error(), "bump the subprotocol version") {
					t.Fatalf("validateTerminalWireManifest(%s) error = %v, want version bump", name, validationErr)
				}
			})
		}
	})

	t.Run("Should accept every decimal terminal wire version at least two", func(t *testing.T) {
		t.Parallel()

		manifestPath := filepath.Join("..", "..", defaultTerminalWireManifestPath)
		manifest, err := readTerminalWireManifest(manifestPath)
		if err != nil {
			t.Fatalf("readTerminalWireManifest() error = %v", err)
		}
		for _, version := range []string{"v10", "v19", "v999999999999999999999999999999999999"} {
			t.Run("Should accept "+version, func(t *testing.T) {
				t.Parallel()

				candidate := manifest
				candidate.Subprotocol = "compozy.terminal." + version
				if validationErr := validateTerminalWireManifest(candidate); validationErr != nil {
					t.Fatalf("validateTerminalWireManifest(%s) error = %v", version, validationErr)
				}
			})
		}
	})

	t.Run("Should restore every terminal wire artifact after publication fails", func(t *testing.T) {
		t.Parallel()

		directory := t.TempDir()
		paths := terminalWirePaths{
			manifest:   filepath.Join("..", "..", defaultTerminalWireManifestPath),
			goOutput:   filepath.Join(directory, "opcodes_generated.go"),
			tsOutput:   filepath.Join(directory, "terminal-wire.ts"),
			docsOutput: filepath.Join(directory, "terminal-wire.md"),
		}
		originals := map[string][]byte{
			paths.goOutput:   []byte("original go\n"),
			paths.tsOutput:   []byte("original ts\n"),
			paths.docsOutput: []byte("original docs\n"),
		}
		for path, content := range originals {
			if err := os.WriteFile(path, content, 0o600); err != nil {
				t.Fatalf("os.WriteFile(%q) error = %v", path, err)
			}
		}
		publishErr := errors.New("injected terminal wire publication failure")
		artifacts := []generatedArtifact{
			{path: paths.goOutput, content: []byte("next go\n")},
			{path: paths.tsOutput, content: []byte("next ts\n")},
			{path: paths.docsOutput, content: []byte("next docs\n")},
		}
		err := publishGeneratedArtifactSet(artifacts, func(path string, content []byte) error {
			if path == paths.tsOutput {
				return publishErr
			}
			return publishGeneratedFile(path, content)
		})
		if !errors.Is(err, publishErr) {
			t.Fatalf("publishGeneratedArtifactSet() error = %v, want %v", err, publishErr)
		}
		for path, want := range originals {
			got, readErr := os.ReadFile(path)
			if readErr != nil {
				t.Fatalf("os.ReadFile(%q) error = %v", path, readErr)
			}
			if !bytes.Equal(got, want) {
				t.Fatalf("artifact %q after rollback = %q, want %q", path, got, want)
			}
		}
	})

	t.Run("ShouldWriteAllAndRejectStaleArtifacts", func(t *testing.T) {
		t.Parallel()

		dir := t.TempDir()
		openapiPath := filepath.Join(dir, "openapi", "compozy.json")
		sdkContractsPath := filepath.Join(dir, "sdk", "typescript", "src", "generated", "contracts.ts")

		if err := runWithPaths(
			context.Background(),
			[]string{subcommandAll},
			openapiPath,
			sdkContractsPath,
		); err != nil {
			t.Fatalf("runWithPaths(all) error = %v", err)
		}
		if err := runWithPaths(context.Background(), []string{"check"}, openapiPath, sdkContractsPath); err != nil {
			t.Fatalf("runWithPaths(check) error = %v", err)
		}

		if err := os.WriteFile(openapiPath, []byte("{\"broken\":true}\n"), 0o644); err != nil {
			t.Fatalf("os.WriteFile(%q) error = %v", openapiPath, err)
		}
		err := runWithPaths(context.Background(), []string{"check"}, openapiPath, sdkContractsPath)
		if !errors.Is(err, ErrStaleGeneratedFile) {
			t.Fatalf("runWithPaths(check) error = %v, want ErrStaleGeneratedFile for stale openapi", err)
		}

		if err := writeOpenAPI(context.Background(), openapiPath); err != nil {
			t.Fatalf("writeOpenAPI(%q) error = %v", openapiPath, err)
		}
		if err := os.WriteFile(sdkContractsPath, []byte("export type Broken = true;\n"), 0o644); err != nil {
			t.Fatalf("os.WriteFile(%q) error = %v", sdkContractsPath, err)
		}
		err = runWithPaths(context.Background(), []string{"check"}, openapiPath, sdkContractsPath)
		if !errors.Is(err, ErrStaleGeneratedFile) {
			t.Fatalf("runWithPaths(check) error = %v, want ErrStaleGeneratedFile for stale sdk", err)
		}

		if err := writeSDKContracts(context.Background(), sdkContractsPath); err != nil {
			t.Fatalf("writeSDKContracts(%q) error = %v", sdkContractsPath, err)
		}
		loopEnumsPath := loopEnumsPathFor(openapiPath)
		if err := os.WriteFile(loopEnumsPath, []byte("export const Broken = true;\n"), 0o644); err != nil {
			t.Fatalf("os.WriteFile(%q) error = %v", loopEnumsPath, err)
		}
		err = runWithPaths(context.Background(), []string{"check"}, openapiPath, sdkContractsPath)
		if !errors.Is(err, ErrStaleGeneratedFile) {
			t.Fatalf("runWithPaths(check) error = %v, want ErrStaleGeneratedFile for stale loop enums", err)
		}
	})

	t.Run("Should reject a stale generated Go contract through the global check", func(t *testing.T) {
		t.Parallel()

		dir := t.TempDir()
		openapiPath := filepath.Join(dir, "openapi", "compozy.json")
		sdkContractsPath := filepath.Join(dir, "sdk", "typescript", "contracts.ts")
		sdkGoContractsPath := filepath.Join(dir, "sdk", "go", "contracts")
		if err := runWithAllPaths(
			context.Background(),
			[]string{subcommandAll},
			openapiPath,
			sdkContractsPath,
			sdkGoContractsPath,
		); err != nil {
			t.Fatalf("runWithAllPaths(all) error = %v", err)
		}

		generated, err := sdkgo.Generate()
		if err != nil {
			t.Fatalf("sdkgo.Generate() error = %v", err)
		}
		name := generated.FileNames()[0]
		path := filepath.Join(sdkGoContractsPath, name)
		content, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("os.ReadFile(%q) error = %v", path, err)
		}
		if len(content) == 0 {
			t.Fatalf("generated contract %q is empty", path)
		}
		content[len(content)-1] ^= 1
		if err := os.WriteFile(path, content, 0o600); err != nil {
			t.Fatalf("os.WriteFile(%q) error = %v", path, err)
		}

		err = runWithAllPaths(
			context.Background(),
			[]string{"check"},
			openapiPath,
			sdkContractsPath,
			sdkGoContractsPath,
		)
		if !errors.Is(err, ErrStaleGeneratedFile) || !strings.Contains(err.Error(), name) {
			t.Fatalf("runWithAllPaths(check) error = %v, want stale %s", err, name)
		}
	})
}

func TestDescribeContractDrift(t *testing.T) {
	t.Parallel()

	t.Run("Should reject changed describe contracts in both SDK representations", func(t *testing.T) {
		t.Parallel()

		dir := t.TempDir()
		typeScriptPath := filepath.Join(dir, "contracts.ts")
		goPath := filepath.Join(dir, "contracts")
		ctx := context.Background()
		if err := writeSDKContracts(ctx, typeScriptPath); err != nil {
			t.Fatalf("writeSDKContracts() error = %v", err)
		}
		if err := writeSDKGoContracts(goPath); err != nil {
			t.Fatalf("writeSDKGoContracts() error = %v", err)
		}

		typeScriptGenerator := func(ctx context.Context, path string) ([]byte, error) {
			content, err := generateFormattedSDKContracts(ctx, path)
			if err != nil {
				return nil, err
			}
			return bytes.Replace(
				content,
				[]byte("export interface DescribePayload {"),
				[]byte("export interface DescribePayload {\n  drift_probe?: string;"),
				1,
			), nil
		}
		if err := checkSDKContractsWith(
			ctx,
			typeScriptPath,
			typeScriptGenerator,
		); !errors.Is(err, ErrStaleGeneratedFile) {
			t.Fatalf("checkSDKContractsWith() error = %v, want describe drift", err)
		}

		goGenerator := func() (sdkgo.Result, error) {
			result, err := sdkgo.Generate()
			if err != nil {
				return sdkgo.Result{}, err
			}
			for name, content := range result.Files {
				if !bytes.Contains(content, []byte("type DescribePayload struct")) {
					continue
				}
				result.Files[name] = bytes.Replace(
					content,
					[]byte("type DescribePayload struct {"),
					[]byte("type DescribePayload struct {\n\tDriftProbe string `json:\"drift_probe,omitempty\"`"),
					1,
				)
				break
			}
			return result, nil
		}
		if err := checkSDKGoContractsWith(goPath, goGenerator); !errors.Is(err, ErrStaleGeneratedFile) {
			t.Fatalf("checkSDKGoContractsWith() error = %v, want describe drift", err)
		}
	})
}

