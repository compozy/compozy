#!/usr/bin/env bun
// Mirrors what the MCP OAuth callback page (internal/api/mcpoauthpage) embeds: theme tokens taken
// from packages/ui, the brand symbol and Atmosphere visuals from packages/brand, and the product's
// self-hosted faces. The page is served by the daemon at its loopback redirect URI, outside the
// web bundle, so it carries its own copies. Approved prototype: web/src/drafts/mcp-oauth-callback.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const root = process.cwd();
const args = new Set(process.argv.slice(2));
const output = "internal/api/mcpoauthpage/assets";
const resolve = createRequire(join(root, "desktop/package.json")).resolve;
const brand = join(root, "packages/brand/public/brand");

// Page aliases → canonical @compozy/ui tokens.
const TOKENS = {
  ink: "color-rail",
  surface: "color-surface-2",
  line: "color-line",
  "line-strong": "color-line-strong",
  fg: "color-fg",
  strong: "color-fg-strong",
  muted: "color-muted-foreground",
  primary: "color-primary",
  "primary-hover": "color-primary-hover",
  "primary-ink": "color-primary-foreground",
  // Volt-to-cyan is the live signal on ink; paper keeps the brand blue.
  live: "color-brand-cyan",
  selection: "color-brand-tint",
  "focus-ring": "theme-shadow-focus-ring",
  success: "color-success",
  warning: "color-warning",
  danger: "color-destructive",
  sans: "font-sans",
  mono: "font-mono",
  display: "font-display",
  ease: "ease-out",
};
/** Light-theme aliases whose value comes from another canonical token. */
const LIGHT_OVERRIDES = { live: "color-brand" };

const FONTS = [
  ["figtree.woff2", "@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2"],
  [
    "instrument-sans.woff2",
    "@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2",
  ],
  ["geist-mono.woff2", "@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2"],
];

const IMAGES = [
  ["symbol.png", join(brand, "png/compozy-symbol-192.png")],
  ["converge.jpg", join(brand, "visuals/converge-1280.jpg")],
  ["horizon.jpg", join(brand, "visuals/horizon-1280.jpg")],
];

const files = [
  ["tokens.gen.css", Buffer.from(tokensCSS(), "utf8")],
  ...FONTS.map(([name, source]) => [name, readFileSync(resolve(source))]),
  ...IMAGES.map(([name, source]) => [name, readFileSync(source)]),
];

const drifted = [];
for (const [name, next] of files) {
  const path = join(root, output, name);
  if (readCurrent(path).equals(next)) continue;
  drifted.push(join(output, name));
  if (args.has("--write")) {
    mkdirSync(join(root, output), { recursive: true });
    writeFileSync(path, next);
  }
}

if (args.has("--write") || drifted.length === 0) process.exit(0);
process.stdout.write(
  `${output} is out of sync with packages/ui, packages/brand and the bundled fonts:\n` +
    drifted.map(file => `  ${file}\n`).join("") +
    "Run make codegen or scripts/sync-mcp-oauth-page-assets.mjs --write.\n"
);
if (args.has("--check")) process.exit(1);

function tokensCSS() {
  const dark = readFileSync(join(root, "packages/ui/src/tokens.css"), "utf8");
  const light = readFileSync(join(root, "packages/ui/src/tokens-light.css"), "utf8");
  const darkLines = Object.entries(TOKENS).map(([alias, canonical]) => {
    const value = tokenValue(dark, canonical);
    if (!value) throw new Error(`Canonical token --${canonical} is missing.`);
    return `  --${alias}: ${value};`;
  });
  // Tokens the light theme does not re-declare (fonts, easing) keep their dark value.
  const lightLines = Object.entries(TOKENS).flatMap(([alias, canonical]) => {
    const override = LIGHT_OVERRIDES[alias];
    const value = override
      ? (tokenValue(light, override) ?? tokenValue(dark, override))
      : tokenValue(light, canonical);
    return value ? [`    --${alias}: ${value};`] : [];
  });
  return (
    "/* Generated by scripts/sync-mcp-oauth-page-assets.mjs from packages/ui tokens. */\n" +
    `:root {\n  color-scheme: dark;\n${darkLines.join("\n")}\n}\n` +
    `@media (prefers-color-scheme: light) {\n  :root {\n    color-scheme: light;\n` +
    `${lightLines.join("\n")}\n  }\n}\n`
  );
}

function tokenValue(source, name) {
  const value = new RegExp(`^\\s*--${name}:\\s*([^;]+);`, "mu").exec(source)?.[1];
  // The page cannot know the operator's Appearance font: drop the `--user-font-*` head the web
  // runtime fills, which is undefined here and would void the whole stack.
  return value
    ?.replace(/\s+/gu, " ")
    .trim()
    .replace(/^var\(--user-font-[a-z]+\),\s*/u, "");
}

function readCurrent(path) {
  try {
    return readFileSync(path);
  } catch (error) {
    if (error.code === "ENOENT") return Buffer.alloc(0);
    throw error;
  }
}
